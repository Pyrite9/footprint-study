-- 발자국 물리적 데이터 모델 v4(PostgreSQL). model.py에서 생성함. 직접 고치지 말 것

-- 회원: 교수 또는 학생 계정 하나
CREATE TABLE member (
    id                        bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                     varchar(255)   NOT NULL UNIQUE,
    password                  varchar(255),
    name                      varchar(255)   NOT NULL,
    member_type               varchar(255)   NOT NULL,
    privacy_consented_at      timestamp,
    CHECK (member_type IN ('PROFESSOR', 'STUDENT'))  -- 회원 유형은 교수와 학생 중 하나
);

-- 과제: 교수가 만든 과제 하나
CREATE TABLE assignment (
    id                        bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                     varchar(255)   NOT NULL,
    start_date                date           NOT NULL,
    end_date                  date           NOT NULL,
    professor_id              bigint         NOT NULL REFERENCES member (id),
    phase                     varchar(255)   NOT NULL,
    evaluation_started_at     timestamp,
    CHECK (phase IN ('RECORDING', 'EVALUATION')),  -- 과제 단계는 기록과 평가 중 하나
    CHECK (end_date >= start_date),  -- 종료일은 시작일과 같거나 뒤
    CHECK ((phase = 'RECORDING' AND evaluation_started_at IS NULL) OR (phase = 'EVALUATION' AND evaluation_started_at IS NOT NULL))  -- 평가 시작 시각은 평가 단계에서만 있음
);

-- 조: 과제에 속한 조 하나
CREATE TABLE team (
    id                        bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id             bigint         NOT NULL REFERENCES assignment (id),
    name                      varchar(255)   NOT NULL,
    invite_code               varchar(255)   UNIQUE
);

-- 조 참여: 회원 한 명이 조 하나에 참여한 기록
CREATE TABLE team_member (
    id                        bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id                   bigint         NOT NULL REFERENCES team (id),
    assignment_id             bigint         NOT NULL REFERENCES assignment (id),
    member_id                 bigint         NOT NULL REFERENCES member (id),
    leader                    boolean        NOT NULL,
    role_name                 varchar(255),
    role_assigned_at          timestamp,
    UNIQUE (assignment_id, member_id)
);

-- 역할 이력: 역할이 한 번 바뀐 기록
CREATE TABLE role_history (
    id                        bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_member_id            bigint         NOT NULL REFERENCES team_member (id),
    previous_role_name        varchar(255)   NOT NULL,
    previous_role_assigned_at timestamp      NOT NULL,
    changed_at                timestamp      NOT NULL
);

-- 조장 교체 이력: 조장이 한 번 바뀐 기록
CREATE TABLE leader_history (
    id                        bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id                   bigint         NOT NULL REFERENCES team (id),
    previous_leader_id        bigint         NOT NULL REFERENCES team_member (id),
    new_leader_id             bigint         NOT NULL REFERENCES team_member (id),
    changed_at                timestamp      NOT NULL,
    CHECK (previous_leader_id <> new_leader_id)  -- 이전 조장과 새 조장은 다른 조원
);

-- 산출물: 조원이 올린 파일 하나
CREATE TABLE deliverable (
    id                        bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_member_id            bigint         NOT NULL REFERENCES team_member (id),
    role_name                 varchar(255)   NOT NULL,
    file_name                 varchar(255)   NOT NULL,
    file_size                 bigint         NOT NULL,
    storage_key               varchar(255)   NOT NULL,
    uploaded_at               timestamp      NOT NULL,
    deleted_at                timestamp,
    CHECK (file_size > 0)  -- 빈 파일은 저장하지 않음
);

-- 기여 항목: 조에 등록한 기여 하나
CREATE TABLE contribution (
    id                        bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id                   bigint         NOT NULL REFERENCES team (id),
    assignee_id               bigint         NOT NULL REFERENCES team_member (id),
    title                     varchar(255)   NOT NULL,
    created_at                timestamp      NOT NULL,
    report_memo               varchar(2000),
    reported_at               timestamp,
    canceled_at               timestamp
);

-- 완료확인: 조원 한 명이 기록 하나를 확인한 것
CREATE TABLE confirmation (
    id                        bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    confirmer_id              bigint         NOT NULL REFERENCES team_member (id),
    deliverable_id            bigint         REFERENCES deliverable (id),
    contribution_id           bigint         REFERENCES contribution (id),
    confirmed_at              timestamp      NOT NULL,
    canceled_at               timestamp,
    CHECK ((deliverable_id IS NOT NULL AND contribution_id IS NULL) OR (deliverable_id IS NULL AND contribution_id IS NOT NULL))  -- 확인 대상은 산출물과 기여 항목 중 하나
);

-- 평가: 평가자 한 명이 대상 한 명을 평가한 것
CREATE TABLE evaluation (
    id                        bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluator_id              bigint         NOT NULL REFERENCES team_member (id),
    target_id                 bigint         NOT NULL REFERENCES team_member (id),
    goal_sharing              integer        NOT NULL,
    role_fulfillment          integer        NOT NULL,
    encouragement             integer        NOT NULL,
    online_communication      integer        NOT NULL,
    offline_communication     integer        NOT NULL,
    progress_check            integer        NOT NULL,
    comment                   varchar(2000),
    submitted_at              timestamp      NOT NULL,
    UNIQUE (evaluator_id, target_id),
    CHECK (evaluator_id <> target_id),  -- 자기 자신은 평가하지 않음
    CHECK (goal_sharing BETWEEN 1 AND 5 AND role_fulfillment BETWEEN 1 AND 5 AND encouragement BETWEEN 1 AND 5 AND online_communication BETWEEN 1 AND 5 AND offline_communication BETWEEN 1 AND 5 AND progress_check BETWEEN 1 AND 5)  -- 점수 6개는 모두 1~5
);

-- 평가 임시 저장: 제출 전 평가 대상 한 명에 대한 입력값
CREATE TABLE evaluation_draft (
    id                        bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluator_id              bigint         NOT NULL REFERENCES team_member (id),
    target_id                 bigint         NOT NULL REFERENCES team_member (id),
    goal_sharing              integer,
    role_fulfillment          integer,
    encouragement             integer,
    online_communication      integer,
    offline_communication     integer,
    progress_check            integer,
    comment                   varchar(2000),
    saved_at                  timestamp      NOT NULL,
    UNIQUE (evaluator_id, target_id),
    CHECK (evaluator_id <> target_id),  -- 자기 자신은 평가하지 않음
    CHECK (goal_sharing BETWEEN 1 AND 5 AND role_fulfillment BETWEEN 1 AND 5 AND encouragement BETWEEN 1 AND 5 AND online_communication BETWEEN 1 AND 5 AND offline_communication BETWEEN 1 AND 5 AND progress_check BETWEEN 1 AND 5)  -- 고른 점수는 1~5. 고르지 않은 점수는 비워 둠
);

-- 알림: 회원 한 명에게 보낸 알림 하나
CREATE TABLE notification (
    id                        bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id              bigint         NOT NULL REFERENCES member (id),
    team_id                   bigint         NOT NULL REFERENCES team (id),
    type                      varchar(255)   NOT NULL,
    message                   varchar(255)   NOT NULL,
    created_at                timestamp      NOT NULL,
    read_at                   timestamp,
    CHECK (type IN ('EVALUATION_STARTED', 'CONTRIBUTION_ASSIGNED', 'CONTRIBUTION_REPORTED'))  -- 알림 종류는 세 가지 중 하나
);
