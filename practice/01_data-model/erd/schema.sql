-- 발자국 물리적 데이터 모델 v5(PostgreSQL)
-- v4는 model.py에서 생성했으나 model.py가 저장소에 없어, v5부터는 이 파일을 직접 고침
-- 이름 규칙: 기본 키 약어_id, 외래 키 [역할_]약어_id, 제약·인덱스 pk_ fk_ uk_ ck_ ix_ + 테이블 약어
-- 약어는 erd_canvas.html 왼쪽 패널의 "약어 범례"와 보고서 원고 [표 3]에 있음

-- 회원(mbr): 교수 또는 학생 계정 하나
CREATE TABLE member (
    mbr_id                bigint         GENERATED BY DEFAULT AS IDENTITY,
    email                 varchar(255)   NOT NULL,
    password              varchar(60),
    name                  varchar(255)   NOT NULL,
    mbr_type              varchar(20)    NOT NULL,
    consented_at          timestamp,
    CONSTRAINT pk_mbr PRIMARY KEY (mbr_id),
    CONSTRAINT uk_mbr_email UNIQUE (email),
    CONSTRAINT ck_mbr_type CHECK (mbr_type IN ('PROFESSOR', 'STUDENT'))  -- 회원 유형은 교수와 학생 중 하나
);

-- 과제(asgn): 교수가 만든 과제 하나
CREATE TABLE assignment (
    asgn_id               bigint         GENERATED BY DEFAULT AS IDENTITY,
    title                 varchar(255)   NOT NULL,
    start_date            date           NOT NULL,
    end_date              date           NOT NULL,
    prof_mbr_id           bigint         NOT NULL,
    phase                 varchar(20)    NOT NULL,
    eval_started_at       timestamp,
    CONSTRAINT pk_asgn PRIMARY KEY (asgn_id),
    CONSTRAINT fk_asgn_prof_mbr FOREIGN KEY (prof_mbr_id) REFERENCES member (mbr_id),
    CONSTRAINT ck_asgn_phase CHECK (phase IN ('RECORDING', 'EVALUATION')),  -- 과제 단계는 기록과 평가 중 하나
    CONSTRAINT ck_asgn_period CHECK (end_date >= start_date),  -- 종료일은 시작일과 같거나 뒤
    CONSTRAINT ck_asgn_eval_started CHECK ((phase = 'RECORDING' AND eval_started_at IS NULL) OR (phase = 'EVALUATION' AND eval_started_at IS NOT NULL))  -- 평가 시작 시각은 평가 단계에서만 있음
);

-- 조(team): 과제에 속한 조 하나
CREATE TABLE team (
    team_id               bigint         GENERATED BY DEFAULT AS IDENTITY,
    asgn_id               bigint         NOT NULL,
    name                  varchar(255)   NOT NULL,
    invite_code           varchar(36),
    CONSTRAINT pk_team PRIMARY KEY (team_id),
    CONSTRAINT fk_team_asgn FOREIGN KEY (asgn_id) REFERENCES assignment (asgn_id),
    CONSTRAINT uk_team_invite_code UNIQUE (invite_code)
);

-- 조 참여(tmbr): 회원 한 명이 조 하나에 참여한 기록
CREATE TABLE team_member (
    tmbr_id               bigint         GENERATED BY DEFAULT AS IDENTITY,
    team_id               bigint         NOT NULL,
    asgn_id               bigint         NOT NULL,
    mbr_id                bigint         NOT NULL,
    leader                boolean        NOT NULL,
    role_name             varchar(255),
    role_assigned_at      timestamp,
    CONSTRAINT pk_tmbr PRIMARY KEY (tmbr_id),
    CONSTRAINT fk_tmbr_team FOREIGN KEY (team_id) REFERENCES team (team_id),
    CONSTRAINT fk_tmbr_asgn FOREIGN KEY (asgn_id) REFERENCES assignment (asgn_id),
    CONSTRAINT fk_tmbr_mbr FOREIGN KEY (mbr_id) REFERENCES member (mbr_id),
    CONSTRAINT uk_tmbr_asgn_mbr UNIQUE (asgn_id, mbr_id)  -- 같은 과제에서 회원 한 명은 한 조에만 참여
);

-- 역할 이력(rolh): 역할이 한 번 바뀐 기록
CREATE TABLE role_history (
    rolh_id               bigint         GENERATED BY DEFAULT AS IDENTITY,
    tmbr_id               bigint         NOT NULL,
    prev_role_name        varchar(255)   NOT NULL,
    prev_role_assigned_at timestamp      NOT NULL,
    changed_at            timestamp      NOT NULL,
    CONSTRAINT pk_rolh PRIMARY KEY (rolh_id),
    CONSTRAINT fk_rolh_tmbr FOREIGN KEY (tmbr_id) REFERENCES team_member (tmbr_id)
);

-- 조장 교체 이력(ldrh): 조장이 한 번 바뀐 기록
CREATE TABLE leader_history (
    ldrh_id               bigint         GENERATED BY DEFAULT AS IDENTITY,
    team_id               bigint         NOT NULL,
    prev_tmbr_id          bigint         NOT NULL,
    new_tmbr_id           bigint         NOT NULL,
    changed_at            timestamp      NOT NULL,
    CONSTRAINT pk_ldrh PRIMARY KEY (ldrh_id),
    CONSTRAINT fk_ldrh_team FOREIGN KEY (team_id) REFERENCES team (team_id),
    CONSTRAINT fk_ldrh_prev_tmbr FOREIGN KEY (prev_tmbr_id) REFERENCES team_member (tmbr_id),
    CONSTRAINT fk_ldrh_new_tmbr FOREIGN KEY (new_tmbr_id) REFERENCES team_member (tmbr_id),
    CONSTRAINT ck_ldrh_diff CHECK (prev_tmbr_id <> new_tmbr_id)  -- 이전 조장과 새 조장은 다른 조원
);

-- 산출물(dlvr): 조원이 올린 파일 하나
CREATE TABLE deliverable (
    dlvr_id               bigint         GENERATED BY DEFAULT AS IDENTITY,
    tmbr_id               bigint         NOT NULL,
    role_name             varchar(255)   NOT NULL,
    file_name             varchar(255)   NOT NULL,
    file_size             bigint         NOT NULL,
    storage_key           varchar(36)    NOT NULL,
    uploaded_at           timestamp      NOT NULL,
    deleted_at            timestamp,
    CONSTRAINT pk_dlvr PRIMARY KEY (dlvr_id),
    CONSTRAINT fk_dlvr_tmbr FOREIGN KEY (tmbr_id) REFERENCES team_member (tmbr_id),
    CONSTRAINT ck_dlvr_size CHECK (file_size > 0)  -- 빈 파일은 저장하지 않음
);

-- 기여 항목(ctrb): 조에 등록한 기여 하나
CREATE TABLE contribution (
    ctrb_id               bigint         GENERATED BY DEFAULT AS IDENTITY,
    team_id               bigint         NOT NULL,
    chrg_tmbr_id          bigint         NOT NULL,
    title                 varchar(255)   NOT NULL,
    created_at            timestamp      NOT NULL,
    report_memo           varchar(2000),
    reported_at           timestamp,
    canceled_at           timestamp,
    CONSTRAINT pk_ctrb PRIMARY KEY (ctrb_id),
    CONSTRAINT fk_ctrb_team FOREIGN KEY (team_id) REFERENCES team (team_id),
    CONSTRAINT fk_ctrb_chrg_tmbr FOREIGN KEY (chrg_tmbr_id) REFERENCES team_member (tmbr_id)
);

-- 완료확인(cnfm): 조원 한 명이 기록 하나를 확인한 것
CREATE TABLE confirmation (
    cnfm_id               bigint         GENERATED BY DEFAULT AS IDENTITY,
    cnfr_tmbr_id          bigint         NOT NULL,
    dlvr_id               bigint,
    ctrb_id               bigint,
    confirmed_at          timestamp      NOT NULL,
    canceled_at           timestamp,
    CONSTRAINT pk_cnfm PRIMARY KEY (cnfm_id),
    CONSTRAINT fk_cnfm_cnfr_tmbr FOREIGN KEY (cnfr_tmbr_id) REFERENCES team_member (tmbr_id),
    CONSTRAINT fk_cnfm_dlvr FOREIGN KEY (dlvr_id) REFERENCES deliverable (dlvr_id),
    CONSTRAINT fk_cnfm_ctrb FOREIGN KEY (ctrb_id) REFERENCES contribution (ctrb_id),
    CONSTRAINT ck_cnfm_target CHECK ((dlvr_id IS NOT NULL AND ctrb_id IS NULL) OR (dlvr_id IS NULL AND ctrb_id IS NOT NULL))  -- 확인 대상은 산출물과 기여 항목 중 하나
);

-- 평가(eval): 평가자 한 명이 대상 한 명을 평가한 것
CREATE TABLE evaluation (
    eval_id               bigint         GENERATED BY DEFAULT AS IDENTITY,
    evlr_tmbr_id          bigint         NOT NULL,
    trgt_tmbr_id          bigint         NOT NULL,
    goal_sharing          integer        NOT NULL,
    role_fulfillment      integer        NOT NULL,
    encouragement         integer        NOT NULL,
    online_talk           integer        NOT NULL,
    offline_talk          integer        NOT NULL,
    progress_check        integer        NOT NULL,
    comment               varchar(2000),
    submitted_at          timestamp      NOT NULL,
    CONSTRAINT pk_eval PRIMARY KEY (eval_id),
    CONSTRAINT fk_eval_evlr_tmbr FOREIGN KEY (evlr_tmbr_id) REFERENCES team_member (tmbr_id),
    CONSTRAINT fk_eval_trgt_tmbr FOREIGN KEY (trgt_tmbr_id) REFERENCES team_member (tmbr_id),
    CONSTRAINT uk_eval_evlr_trgt UNIQUE (evlr_tmbr_id, trgt_tmbr_id),  -- 같은 평가자는 같은 대상을 한 번만 평가
    CONSTRAINT ck_eval_self CHECK (evlr_tmbr_id <> trgt_tmbr_id),  -- 자기 자신은 평가하지 않음
    CONSTRAINT ck_eval_score CHECK (goal_sharing BETWEEN 1 AND 5 AND role_fulfillment BETWEEN 1 AND 5 AND encouragement BETWEEN 1 AND 5 AND online_talk BETWEEN 1 AND 5 AND offline_talk BETWEEN 1 AND 5 AND progress_check BETWEEN 1 AND 5)  -- 점수 6개는 모두 1~5
);

-- 평가 임시 저장(evdf): 제출 전 평가 대상 한 명에 대한 입력값
CREATE TABLE evaluation_draft (
    evdf_id               bigint         GENERATED BY DEFAULT AS IDENTITY,
    evlr_tmbr_id          bigint         NOT NULL,
    trgt_tmbr_id          bigint         NOT NULL,
    goal_sharing          integer,
    role_fulfillment      integer,
    encouragement         integer,
    online_talk           integer,
    offline_talk          integer,
    progress_check        integer,
    comment               varchar(2000),
    saved_at              timestamp      NOT NULL,
    CONSTRAINT pk_evdf PRIMARY KEY (evdf_id),
    CONSTRAINT fk_evdf_evlr_tmbr FOREIGN KEY (evlr_tmbr_id) REFERENCES team_member (tmbr_id),
    CONSTRAINT fk_evdf_trgt_tmbr FOREIGN KEY (trgt_tmbr_id) REFERENCES team_member (tmbr_id),
    CONSTRAINT uk_evdf_evlr_trgt UNIQUE (evlr_tmbr_id, trgt_tmbr_id),  -- 평가자와 대상 조합마다 하나
    CONSTRAINT ck_evdf_self CHECK (evlr_tmbr_id <> trgt_tmbr_id),  -- 자기 자신은 평가하지 않음
    CONSTRAINT ck_evdf_score CHECK (goal_sharing BETWEEN 1 AND 5 AND role_fulfillment BETWEEN 1 AND 5 AND encouragement BETWEEN 1 AND 5 AND online_talk BETWEEN 1 AND 5 AND offline_talk BETWEEN 1 AND 5 AND progress_check BETWEEN 1 AND 5)  -- 고른 점수는 1~5. 고르지 않은 점수는 비워 둠
);

-- 알림(noti): 회원 한 명에게 보낸 알림 하나
CREATE TABLE notification (
    noti_id               bigint         GENERATED BY DEFAULT AS IDENTITY,
    rcvr_mbr_id           bigint         NOT NULL,
    team_id               bigint         NOT NULL,
    type                  varchar(30)    NOT NULL,
    message               varchar(1000)  NOT NULL,
    created_at            timestamp      NOT NULL,
    read_at               timestamp,
    CONSTRAINT pk_noti PRIMARY KEY (noti_id),
    CONSTRAINT fk_noti_rcvr_mbr FOREIGN KEY (rcvr_mbr_id) REFERENCES member (mbr_id),
    CONSTRAINT fk_noti_team FOREIGN KEY (team_id) REFERENCES team (team_id),
    CONSTRAINT ck_noti_type CHECK (type IN ('EVALUATION_STARTED', 'CONTRIBUTION_ASSIGNED', 'CONTRIBUTION_REPORTED'))  -- 알림 종류는 세 가지 중 하나
);

-- 부분 UNIQUE: WHERE 조건에 맞는 행끼리만 중복을 막음. 제약(CONSTRAINT)으로는 조건을 쓸 수 없어 인덱스로 만듦
CREATE UNIQUE INDEX uk_tmbr_leader ON team_member (team_id) WHERE leader;  -- 조장은 조마다 한 명
CREATE UNIQUE INDEX uk_cnfm_dlvr_cnfr ON confirmation (dlvr_id, cnfr_tmbr_id) WHERE canceled_at IS NULL AND dlvr_id IS NOT NULL;  -- 취소하지 않은 산출물 확인은 조원마다 하나
CREATE UNIQUE INDEX uk_cnfm_ctrb_cnfr ON confirmation (ctrb_id, cnfr_tmbr_id) WHERE canceled_at IS NULL AND ctrb_id IS NOT NULL;  -- 취소하지 않은 기여 항목 확인은 조원마다 하나

-- 조회용 인덱스: 외래 키에는 인덱스가 자동으로 생기지 않음. 조회 경로가 있는 곳만 만듦
CREATE INDEX ix_tmbr_mbr ON team_member (mbr_id);  -- 회원 기준 조회(내 조 목록). uk_tmbr_asgn_mbr는 asgn_id가 앞이라 못 씀
CREATE INDEX ix_tmbr_team ON team_member (team_id);  -- 조 기준 조회(조원 목록). uk_tmbr_leader는 조장 행만 담아서 못 씀
CREATE INDEX ix_noti_rcvr ON notification (rcvr_mbr_id);  -- 받는 회원 기준 조회(알림 목록)
